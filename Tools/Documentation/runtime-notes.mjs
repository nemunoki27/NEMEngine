export function runtimeMemberDescription(type, name) {
	const exact = memberNotes[`${type}.${name}`];
	if (exact) return exact;
	if (name === 'Resume') return '一時停止中の再生や計測を、停止した位置から再開します。';
	if (name === 'IsFinished') return '最後まで再生が完了したかを取得します。';
	if (name === 'CurrentTime') return '現在の再生時刻を秒で取得します。';
	if (name === 'GetRenderSettings') return 'Renderer個別の描画状態を取得します。編集後はSetRenderSettingsで適用します。';
	if (name === 'SetRenderSettings') return 'Renderer個別の描画・深度・ステンシル設定をまとめて適用します。';
	if ((type === 'TimelinePlayer' || type === 'TimelineContext') && name === 'IsWindowOpen')
		return '名前を指定した受付区間が現在開いているかを取得します。連続攻撃などの入力受付に使います。';
	if ((type === 'TimelinePlayer' || type === 'TimelineContext') && /^Get(?:Bool|Float|Int|String|Vector3)$/.test(name))
		return '名前を指定し、Timelineに設定されたパラメーターを戻り値の型で取得します。';
	if (type === 'TimelinePlayer' && /^Set(?:String|Vector3)$/.test(name))
		return '名前を指定し、Timelineのパラメーターを引数の型で変更します。';
	return null;
}
