		const operator = { Addition: '加算', Subtraction: '減算', Multiply: '乗算', Division: '除算', Equality: '等値比較', Inequality: '不等値比較', UnaryNegation: '符号反転', Implicit: '暗黙の型変換', Explicit: '明示的な型変換', True: '有効性判定', False: '無効性判定' }[member.name.slice(3)] || '演算';
