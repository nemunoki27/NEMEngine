			GetSettings: 'Emitter・Phase・Module・Trail・GPU設定を持つ編集用Snapshotを取得します。変更後はSetSettingsへ戻します。',
			SetSettings: '編集済みSnapshotをこのParticleSystemへ反映します。GetSettingsの戻り値だけを書き換えて終了しないでください。',
			IsAlive: '発生や生存粒子が残っているかを調べます。isPlayingと異なり、停止後に残った粒子を含む終了判定へ使います。',
