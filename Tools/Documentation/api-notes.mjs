export function guideFor(type) {

	const name = type.name;
	if (type.baseType === 'System.Attribute') return 'script-attributes';
	if (['GameObject', 'Component', 'Object'].includes(name)) return 'entity';
	if (/^Particle|^Curve|Easing|GeometrySettings/.test(name)) return 'particles';
	if (/Camera|Exposure/.test(name)) return 'camera';
	if (/RenderPass/.test(name)) return 'post-process';
	if (/Graphics|DisplayOutput|Screen/.test(name)) return 'project-settings';
	if (/Input|KeyCode|Gamepad|MouseButton/.test(name)) return 'input';
	if (/Audio/.test(name)) return 'audio';
	if (/Animation|Animator|Skinned/.test(name)) return 'animation';
	if (/Collision|Physics|Rigidbody|Joint|Ray|ForceMode/.test(name)) return 'physics';
	if (/Canvas|^UI|IUIButton/.test(name)) return 'ui';
	if (/Material/.test(name)) return 'materials';
	if (/TextRenderer|Font|TextCharacter/.test(name)) return 'text';
	if (/Texture|Asset|Mesh|Prefab|ShaderGraph/.test(name)) return 'assets';
	if (/Csv|Json|TextAsset/.test(name)) return 'data';
	if (/Scene|Transform|Space/.test(name)) return 'scene';
	if (/Renderer|Outline|LineDraw|LinePoint|Billboard/.test(name)) return 'rendering';
	return 'scripting';
}

