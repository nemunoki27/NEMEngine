#pragma once

//============================================================================
//	include
//============================================================================
#include <cstdint>
#include <Windows.h>

namespace Engine {

	//============================================================================
	//	EditorShortcutState class
	//	表示切替の押下と未処理要求を保持する
	//============================================================================
	class EditorShortcutState {
	public:
		//========================================================================
		//	public Methods
		//========================================================================

		// 入力メッセージから切替要求を記録する
		void ProcessMessage(UINT message, WPARAM key, LPARAM flags);
		// 最初の安全地点で切替要求を取り出す
		bool Consume();
		// フォーカス喪失時に入力を解除する
		void Reset();

	private:
		//========================================================================
		//	private Methods
		//========================================================================

		//--------- variables ----------------------------------------------------

		bool tabDown_ = false;
		bool escapeDown_ = false;
		uint32_t pendingCount_ = 0;
	};
}
