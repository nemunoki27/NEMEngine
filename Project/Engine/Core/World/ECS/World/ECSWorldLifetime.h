#pragma once

namespace Engine {

	//============================================================================
	//	ECSWorldLifetime class
	//	Worldの終了状態だけを外部へ伝える
	//============================================================================
	class ECSWorldLifetime {
	public:
		//========================================================================
		//	public Methods
		//========================================================================

		// 終了していないか
		bool IsAlive() const { return alive_; }
		// 終了したWorldへの処理再開を拒否する
		void ThrowIfEnded() const;

	private:
		//========================================================================
		//	private Methods
		//========================================================================

		friend class ECSWorld;

		//--------- variables ----------------------------------------------------

		bool alive_ = true;
	};
}
