Engine::ShaderGraphInputDefault Engine::GetShaderGraphInputDefault(const ShaderGraphNode& node, uint32_t slot) {

	if (node.kind == ShaderGraphNodeKind::MatrixConstruction && slot < node.settings.matrixRows.size()) {
		return { ShaderGraphValueType::Float4, MaterialParameterValue{ node.settings.matrixRows[slot] }, {} };
	}
	for (const auto& entry : kDefaults) {
		if (entry.kind == node.kind && entry.slot == slot) { return entry.input; }
	}
	return {};
}
